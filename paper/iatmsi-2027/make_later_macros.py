#!/usr/bin/env python3
"""Writes later_macros.tex: the numbers that are not in ../analysis/results/*.tex.

Computed here: the read-noise bracket (own repeats, third party, combination), reads per arm, drop probabilities.
Read from files of the competition repository (read-only): the transfer counts (468 runs) and the time ladder.
Typed in, with their source: the compaction counts (see the comments at the end)."""
import math, os, re, json, sys
from scipy.stats import chi2, norm

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "later_macros.tex")
# repository checkout: first argument, else $GEMMA_REPO, else the author's checkout
REPO = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("GEMMA_REPO", "~/Projects/gemma-swe-agent"))
AUD = REPO + "/research/assumptions_2026-10-31"
M = {}


def ci(s, d): return s * math.sqrt(d / chi2.ppf(.975, d)), s * math.sqrt(d / chi2.ppf(.025, d))
# ---- 1a. LOW end: our own byte-identical repeats. Same Kaggle scriptVersionId (same kernel version) for both reads of a pair:
#      v4 352953199 (sub3 27 Sep, sub5 29 Sep), v10.1 353955250 (sub6 30 Sep, sub8 2 Oct), v4h2 354761775 (sub9 3 Oct, sub12 6 Oct),
#      v12 357229750 (sub14 11 Oct, sub21 19 Oct); eval/analysis/out/kaggle_submissions_2026-10-21.json. Reads in tasks of 58.
own = {"v4": [7, 7], "v10.1": [5, 5], "v4h2": [6, 5], "v12": [9, 8]}
own_ss = sum(sum((x - sum(r) / len(r))**2 for x in r) for r in own.values()); own_df = sum(len(r) - 1 for r in own.values())
own_sd = math.sqrt(own_ss / own_df); own_lo, own_hi = ci(own_sd, own_df)
M["ownSD"] = f"{own_sd:.2f}"; M["ownLo"] = f"{own_lo:.2f}"; M["ownHi"] = f"{own_hi:.2f}"; M["ownDf"] = str(own_df); M["ownPairs"] = str(len(own))
# ---- 1b. HIGH end: third-party repeated public-notebook draws, grouped by notebook (not verified identical, draws not kept):
#      pooled SD 1.559 on 23 df, hard-coded in AUD/field/line_stats.py line 21 (origin: AUD/field/scan_all.py, dataset not kept)
th_sd, th_df = 1.559, 23; th_lo, th_hi = ci(th_sd, th_df)
M["thirdSD"] = f"{th_sd:.2f}"; M["thirdLo"] = f"{th_lo:.2f}"; M["thirdHi"] = f"{th_hi:.2f}"; M["thirdDf"] = str(th_df)
# ---- 1c. the audit's combination: third party + our v12 pair + two other-team sets (AUD/field/line_stats.py lines 18-29)
ss = th_sd**2 * th_df + 0.5 + 2.0 + 2.0; df = th_df + 1 + 2 + 1
sd = math.sqrt(ss / df); lo, hi = ci(sd, df)
M["readSD"] = f"{sd:.2f}"; M["readSDlo"] = f"{lo:.2f}"; M["readSDhi"] = f"{hi:.2f}"; M["readSDdf"] = str(df)
# ---- 2. reads per arm to detect a true difference of d tasks, two-sided alpha .05, power .80, equal SD
def n_arm(d, s): return 2 * s**2 * (norm.ppf(.975) + norm.ppf(.80))**2 / d**2
M["nArmOwn"] = str(math.ceil(n_arm(1.5, own_sd))); M["nArmThird"] = str(math.ceil(n_arm(1.5, th_sd))); M["nArmComb"] = str(math.ceil(n_arm(1.5, sd)))
M["nArmOwnThree"] = str(math.ceil(n_arm(3.0, own_sd))); M["nArmThirdThree"] = str(math.ceil(n_arm(3.0, th_sd)))
M["ratioUpper"] = f"{2/th_sd:.1f}"; M["ratioLower"] = f"{2/own_sd:.0f}"
M["readPMThird"] = f"{2*th_sd:.0f}"; M["readPMOwn"] = f"{2*own_sd:.0f}"
# ---- 2b. are the seven A6000 hidden means distinguishable from one common mean? (local solves and hidden reads: table in paper.tex)
import numpy as np
from scipy.stats import spearmanr
loc = [26, 28, 28, 28, 28, 30, 31]                     # local solves (repeat runs averaged: baseline 27,29 -> 28; two rules 31,29 -> 30)
hid = [[6], [6], [6], [9, 8], [10], [8], [9]]          # hidden reads in tasks (0.10 -> 6, 0.15 -> 9, 0.13 -> 8, 0.17 -> 10)
hm = [np.mean(h) for h in hid]
assert abs(spearmanr(loc, hm)[0] - 0.49) < 0.005       # reproduces \rhoA from the generated macros
grand = sum(sum(h) for h in hid) / sum(len(h) for h in hid)
spread = float(np.std(hm, ddof=1)); M["hidSpread"] = f"{spread:.1f}"   # SD across the seven hidden means
def homog(sig):
    Q = sum(len(h) * (np.mean(h) - grand)**2 for h in hid) / sig**2
    return Q, 1 - chi2.cdf(Q, len(hid) - 1)
def pfmt(p): return "below 0.001" if p < 0.001 else f"{p:.2f}"
for tag, s_ in (("Own", own_sd), ("Third", th_sd)):
    M["homogQ" + tag] = f"{homog(s_)[0]:.1f}"; M["homogP" + tag] = pfmt(homog(s_)[1])
    rng = np.random.default_rng(1); rs = []
    for _ in range(20000):
        y = [m + rng.normal() * s_ / np.sqrt(len(h)) for m, h in zip(hm, hid)]
        rs.append(spearmanr(loc, y)[0])
    rs = np.array(rs)
    f_ = lambda v: f"{v:.2f}".replace("-", "\\textminus{}")
    M["simLo" + tag] = f_(np.percentile(rs, 2.5)); M["simHi" + tag] = f_(np.percentile(rs, 97.5)); M["simCrit" + tag] = f"{100*(np.abs(rs) >= 0.79).mean():.0f}"
with open(os.path.join(os.path.dirname(OUT), "table_power.tex"), "w") as fh:
    fh.write("% generated by make_later_macros.py: reads per arm, two-sided alpha .05, power .80, equal SD\n\\begin{tabular}{@{}lrrrr@{}}\n\\toprule\n")
    fh.write("per-read SD & \\multicolumn{4}{c}{true gain (tasks)} \\\\\n\\cmidrule(l){2-5}\n & 1 & 1.5 & 2 & 3 \\\\\n\\midrule\n")
    for lab, s_ in ((f"{own_sd:.2f} (own pairs)", own_sd), (f"{sd:.2f} (combined)", sd), (f"{th_sd:.2f} (third party)", th_sd)):
        fh.write(lab + " & " + " & ".join(str(math.ceil(n_arm(d_, s_))) for d_ in (1, 1.5, 2, 3)) + " \\\\\n")
    fh.write("\\bottomrule\n\\end{tabular}\n")
# ---- 3. the single-read band: drop at <= 0.14 (8 tasks of 58) a candidate whose true mean is the line mean; a read is round(X), X ~ N(mu, s)
LINE = 8.29   # AUD/field/line_stats.py output, "mu_v12b posterior mean 8.29" at sigma = 1.5
M["lineMean"] = f"{LINE:.1f}"
M["pDropOwn"] = f"{100*norm.cdf((8.5 - LINE) / own_sd):.0f}"; M["pDropThird"] = f"{100*norm.cdf((8.5 - LINE) / th_sd):.0f}"
M["pDropAudit"] = "55"   # AUD/field/line_stats.py, sigma=1.5: P(k<=8)=0.55 (posterior predictive, includes uncertainty in the mean)

# ---- 4. transfer: v12 prompt on non-public repositories (P10 collection), AUD/transfer/scripts/solve_by_feature.py inputs
n = k = 0; repos = set()
base = REPO + "/eval/a6000/results/p3_think/items/v12"
feat = {r["id"]: r for r in json.load(open(AUD + "/transfer/out/corpus_features.json"))["heldout1k"]}
for t in os.listdir(base):
    f = os.path.join(base, t, "task_results.jsonl")
    if os.path.exists(f) and t in feat:
        r = json.loads(open(f).readline()); n += 1; k += bool(r.get("resolved")); repos.add(feat[t]["repo"])
M["xferRuns"] = str(n); M["xferSolved"] = str(k); M["xferRepos"] = str(len(repos))
M["xferRate"] = f"{100*k/n:.1f}"; M["xferSE"] = f"{100*math.sqrt(k/n*(1-k/n)/n):.1f}"
# public rate of the same prompt on the paced A6000: 27 and 29 of 74 (draft-emse/source/tables/repeats_box.tex line 7)
for tag, v in (("A", 27), ("B", 29)):
    M["pubRate" + tag] = f"{100*v/74:.0f}"; M["xferRatio" + tag] = f"{(k/n)/(v/74):.2f}"

# ---- 5. time ladder L1: AUD-independent, eval/ladder/l1/analysis.txt
txt = open(REPO + "/eval/ladder/l1/analysis.txt").read()
S = {}
for m in re.finditer(r"^T=(\d+)\s+(\d+)\s+(\d+)\s+(\d+)", txt, re.M):
    S[int(m.group(1))] = tuple(int(m.group(i)) for i in (2, 3, 4))
M["ladNTasks"] = re.search(r"n tasks (\d+)", txt).group(1)
def gain(label, key):
    m = re.search(rf"^{label}.*net ([+-]\d+) \(up (\d+), down (\d+)\)\s+95% CI \[([+-]\d+), ([+-]\d+)\]", txt, re.M)
    g = [x.replace("-", "\\textminus{}") if x[0] == "-" else x for x in m.groups()]
    g = ["0" if x == "+0" else x for x in g]      # print +0 as 0
    M[key + "Net"], M[key + "Up"], M[key + "Down"], M[key + "Lo"], M[key + "Hi"] = g
gain("G6 ", "gSix"); gain("G7 ", "gSeven"); gain("G8 ", "gEight"); gain("28-call truncation", "gCalls"); gain("public shape", "gShape")
NAME = {240: "Four", 300: "Five", 330: "FiveHalf", 360: "Six", 420: "Seven", 480: "Eight"}   # minutes, spelled out (macro names cannot hold digits)
for T in S: M["lad" + NAME[T]] = str(S[T][2])      # solved at 40 calls
M["ladKernel"] = re.search(r"kernel's own solved (\d+)", txt).group(1)

# ---- 6. typed in, with sources
M["compactTok"] = "14{,}336"      # docs/GAPS_2026-10-06.md line 1774
M["compactLo"] = "39"; M["compactHi"] = "42"   # lines 1751 and 1774: v12b_garble 39 of 74, v12 42 of 74 (eval/analysis/compaction_l4.py)
M["compactSolvedLo"] = "14"; M["compactSolvedHi"] = "15"   # line 1751
M["subCtx"] = "0.13"              # sub27, docs/GAPS_2026-10-06.md; LATER-RESULTS-2026-11.md table of hidden reads

with open(OUT, "w") as fh:
    fh.write("% generated by make_later_macros.py; do not edit. Inputs and sources are listed in NOTES.md.\n")
    for key, v in M.items(): fh.write(f"\\newcommand{{\\{key}}}{{{v}}}\n")
print(json.dumps(M, indent=1))
