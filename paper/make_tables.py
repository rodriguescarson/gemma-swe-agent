"""Regenerate every paper table from saved files (paper/EVIDENCE.md: no number enters the paper unless this or a script it
calls rebuilds it). Writes paper/tables/*.md, each stamped with the commit and the input files.
    python paper/make_tables.py
Tables: box_runs (every complete 74-read), paired (net / flips / sign-test p between key runs), aa (the same bundle twice),
deadline (solves kept under a shorter cap, conservative), calibration (box vs hidden; eval/analysis/calibration.py),
l4_screen (the same question on Kaggle's 4xL4, no proxy), hidden_repeats (one bundle submitted twice)."""
from __future__ import annotations

import json
import math
import statistics as st
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "eval" / "a6000" / "results"
OUT = ROOT / "paper" / "tables"
# run -> (bundle, per-task cap in seconds): the bundle's own eval_config
RUNS = {"p4_v12": ("v12", 300), "p4_b1024": ("v12-b1024", 300), "p4_v0t2": ("v0-think", 300), "p4_v13": ("v13", 300),
        "p4_v13r": ("v13 (replicate)", 300), "p4_v14": ("v14", 300), "p4_v15": ("v15", 300), "p4_v12b": ("v12b", 300),
        "p4_v16": ("v16", 300), "p4_v12a": ("v12a", 480), "p4_v12c": ("v12c", 480), "p4_pub024": ("pub024", 480),
        "p4_pub024_6m": ("pub024_6m", 360), "p4_v12r": ("v12 (replicate)", 300)}
PAIRS = [("p4_v13r", "p4_v13"), ("p4_b1024", "p4_v12"), ("p4_v13", "p4_v12"), ("p4_v14", "p4_v13"), ("p4_v15", "p4_v12"),
         ("p4_v12a", "p4_v12"), ("p4_v12b", "p4_v12"), ("p4_v12c", "p4_v12"), ("p4_v12c", "p4_v12a"), ("p4_pub024", "p4_v12"),
         ("p4_pub024_6m", "p4_pub024"), ("p4_v16", "p4_v12"), ("p4_v16", "p4_v12c"), ("p4_v12r", "p4_v12")]


def commit() -> str:
    return subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()


def load(run: str) -> dict[str, dict] | None:
    p = RES / run / "results.jsonl"
    if not p.is_file():
        return None
    rows = {}
    for line in p.read_text().splitlines():
        if line.strip():
            r = json.loads(line)
            rows[r["id"]] = r                    # the last row per id counts (box_p4_gate.py's rule)
    return rows if len(rows) == 74 else None    # only complete 74-reads enter a table


def sign_p(w: int, l: int) -> float:
    n = w + l
    if n == 0:
        return 1.0
    k = min(w, l)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)


def stamp(name: str, inputs: list[str], body: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    head = f"<!-- generated by paper/make_tables.py at commit {commit()} from: {', '.join(inputs)} -->\n"
    (OUT / f"{name}.md").write_text(head + body)


def main() -> int:
    data = {r: load(r) for r in RUNS}
    have = {r: d for r, d in data.items() if d}
    # box_runs
    lines = ["| run | bundle | cap s | solved/74 | mean s/task | rows at cap | 120-task projection h |", "|---|---|---|---|---|---|---|"]
    for r, d in have.items():
        b, cap = RUNS[r]
        secs = [x["secs"] for x in d.values()]
        lines.append(f"| {r} | {b} | {cap} | {sum(bool(x['resolved']) for x in d.values())} | {st.mean(secs):.0f} | "
                     f"{sum(s >= cap - 5 for s in secs)} | {120 * st.mean(secs) / 3600:.1f} |")
    stamp("box_runs", [f"eval/a6000/results/{r}/results.jsonl" for r in have], "\n".join(lines) + "\n")
    # paired
    lines = ["| run A | run B | A solved | B solved | A only | B only | net | flips | sign-test p |", "|---|---|---|---|---|---|---|---|---|"]
    for a, b in PAIRS:
        if a in have and b in have:
            A, B = have[a], have[b]
            ids = set(A) & set(B)
            w = sum(bool(A[i]["resolved"]) and not B[i]["resolved"] for i in ids)
            l = sum(bool(B[i]["resolved"]) and not A[i]["resolved"] for i in ids)
            lines.append(f"| {a} | {b} | {sum(bool(A[i]['resolved']) for i in ids)} | {sum(bool(B[i]['resolved']) for i in ids)} | "
                         f"{w} | {l} | {w - l:+d} | {w + l} | {sign_p(w, l):.3f} |")
    stamp("paired", sorted({f"eval/a6000/results/{r}/results.jsonl" for p in PAIRS for r in p if r in have}), "\n".join(lines) + "\n")
    # aa: the same bundle twice on the box (exact replay = same resolved, calls and patch, seconds within 2 s)
    body, inputs = "", []
    for a, b, name in (("p4_v13", "p4_v13r", "v13"), ("p4_v12", "p4_v12r", "v12")):
        if a in have and b in have:
            A, B = have[a], have[b]
            flips = sorted(i for i in A if bool(A[i]["resolved"]) != bool(B[i]["resolved"]))
            w = sum(bool(B[i]["resolved"]) and not A[i]["resolved"] for i in A)
            exact = sum(bool(A[i]["resolved"]) == bool(B[i]["resolved"]) and A[i].get("calls") == B[i].get("calls")
                        and (A[i].get("patch") or "") == (B[i].get("patch") or "") and abs(A[i]["secs"] - B[i]["secs"]) <= 2
                        for i in A)
            body += (f"Same bundle ({name}), same box, same 74 tasks, two runs: {sum(bool(x['resolved']) for x in A.values())} and "
                     f"{sum(bool(x['resolved']) for x in B.values())} solved; {len(flips)} tasks flipped ({w} gained, "
                     f"{len(flips) - w} lost; sign-test p {sign_p(w, len(flips) - w):.3f}): {', '.join(flips)}; "
                     f"exact replays {exact} of 74.\n")
            inputs += [f"eval/a6000/results/{a}/results.jsonl", f"eval/a6000/results/{b}/results.jsonl"]
    if body:
        stamp("aa", inputs, body)
    # deadline (conservative: a solve is kept only if its run ended before the deadline)
    lines = ["| run | cap s | " + " | ".join(f"{D} s" for D in (180, 210, 240, 270, 300, 360, 480)) + " |", "|---|---|" + "---|" * 7]
    for r in ("p4_v12", "p4_v12b", "p4_v13", "p4_v12a", "p4_pub024", "p4_v12c"):
        if r not in have:
            continue
        cap = RUNS[r][1]
        cells = []
        for D in (180, 210, 240, 270, 300, 360, 480):
            if D > cap:
                cells.append("")
                continue
            kept = sum(bool(x["resolved"]) and (x["secs"] < D - 5 or D == cap) for x in have[r].values())
            cells.append(f"{kept} ({st.mean(min(x['secs'], D) for x in have[r].values()):.0f} s)")
        lines.append(f"| {r} | {cap} | " + " | ".join(cells) + " |")
    stamp("deadline", [f"eval/a6000/results/{r}/results.jsonl" for r in ("p4_v12", "p4_v12b", "p4_v13", "p4_v12a", "p4_pub024", "p4_v12c") if r in have],
          "Solves kept (mean seconds per task) if the per-task cap were D; conservative: a solve counts only if its run ended before D.\n\n"
          + "\n".join(lines) + "\n")
    # l4_screen: the same question on Kaggle's own 4xL4 (no pacing proxy), from the per-task results the kernels saved
    l4 = {}
    for run in ("g4-l4-v4-wh28-p312", "g4-l4-v4h2-p312", "g4-l4-v4h2g-p312", "g4-l4-v12-p312"):
        f = ROOT / "eval" / "kaggle" / run / "results.jsonl"
        if f.is_file():
            rows = {}
            for line in f.read_text().splitlines():
                if line.strip():
                    r = json.loads(line)
                    rows[r["id"]] = r
            l4[run] = rows if len(rows) == 74 else None
    subs = {}
    snaps = sorted((ROOT / "eval" / "analysis" / "out").glob("kaggle_submissions_*.json"))
    if snaps:
        for r in json.loads(snaps[-1].read_text())["submissions"]:
            subs[r["ref"]] = r.get("public_score") or ("RUNTIME" if "runtime" in (r.get("error_description") or "") else
                                                       "PENDING" if "PENDING" in (r.get("status") or "") else "error")
    hidden = {"g4-l4-v4-wh28-p312": ("v4", ["56824301"]), "g4-l4-v4h2-p312": ("v4h2", ["56788077", "56864298"]),
              "g4-l4-v4h2g-p312": ("v4h2g", ["56837573"]), "g4-l4-v12-p312": ("v12", ["57070001"])}
    lines = ["| L4 run | bundle | solved/74 | hidden public (rebuilt scorer) |", "|---|---|---|---|"]
    for run, d in l4.items():
        if d:
            b, refs = hidden[run]
            lines.append(f"| {run} | {b} | {sum(bool(x['resolved']) for x in d.values())} | "
                         f"{', '.join(subs.get(x, '?') for x in refs)} |")
    if l4.get("g4-l4-v4h2g-p312") and l4.get("g4-l4-v4h2-p312"):
        A, B = l4["g4-l4-v4h2g-p312"], l4["g4-l4-v4h2-p312"]
        w = sum(bool(A[i]["resolved"]) and not B[i]["resolved"] for i in A)
        l = sum(bool(B[i]["resolved"]) and not A[i]["resolved"] for i in A)
        lines.append(f"\nPaired on L4, v4h2g vs v4h2: {w} only-A, {l} only-B, sign-test p {sign_p(w, l):.3f}.")
    stamp("l4_screen", [f"eval/kaggle/{r}/results.jsonl" for r in l4] + [str(s.relative_to(ROOT)) for s in snaps[-1:]],
          "\n".join(lines) + "\n")
    # hidden_repeats: the same bundle submitted more than once (post hoc; the scorer was rebuilt about 30 Sep)
    reps = {"v4 (old scorer)": ["56591871", "56655519"], "v10.1": ["56690751", "56765412"], "v4h2": ["56788077", "56864298"],
            "pub024": ["57280385", "57304025"], "v12": ["57070001", "57390142"]}
    lines = ["| bundle | hidden public reads |", "|---|---|"] + [f"| {b} | {', '.join(subs.get(x, '?') for x in refs)} |"
                                                              for b, refs in reps.items()]
    stamp("hidden_repeats", [str(s.relative_to(ROOT)) for s in snaps[-1:]], "\n".join(lines) + "\n")
    # calibration (delegated, so there is one implementation)
    cal = subprocess.run([sys.executable, str(ROOT / "eval" / "analysis" / "calibration.py")], capture_output=True, text=True, cwd=ROOT)
    if cal.returncode == 0:
        stamp("calibration", ["eval/analysis/calibration.py", "eval/analysis/out/kaggle_submissions_*.json", "eval/a6000/results/p4_*"], cal.stdout)
    print(f"tables written to {OUT}: {sorted(p.name for p in OUT.glob('*.md'))}; complete runs: {len(have)} of {len(RUNS)}"
          f"{' (missing: ' + ', '.join(r for r in RUNS if r not in have) + ')' if len(have) < len(RUNS) else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
