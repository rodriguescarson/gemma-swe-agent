"""LaTeX tables for the arXiv paper, generated from saved results (never typed).

    python3 paper/arxiv/make_tex_tables.py     # writes paper/arxiv/tables/*.tex

Uses the same inputs as make_figures.py plus the Harness² Phase 1 archive (eval/a6000/results/h2_gemma)."""
from __future__ import annotations

import importlib.util
import math
import statistics as st
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = HERE / "tables"
spec = importlib.util.spec_from_file_location("figs", HERE / "make_figures.py")
F = importlib.util.module_from_spec(spec)
spec.loader.exec_module(F)
spec2 = importlib.util.spec_from_file_location("h2_read", ROOT / "eval" / "analysis" / "h2_read.py")
H = importlib.util.module_from_spec(spec2)
spec2.loader.exec_module(H)

# run id -> (configuration id, description, per-task cap in seconds)
RUNS = {
    "p4_v0t2": ("v0-think", "starter agent with thinking on", 300),
    "p4_v12": ("v12", "baseline: one agent, thinking on", 300),
    "p4_v12r": ("v12", "baseline, second run", 300),
    "p4_b1024": ("v12-b1024", "baseline, thinking budget 1,024", 300),
    "p4_v13": ("v13", "b1024 + two prompt rules (L1, L2)", 300),
    "p4_v13r": ("v13", "same, second run", 300),
    "p4_v14": ("v14", "v13 + two per-task rules", 300),
    "p4_v15": ("v15", "baseline + L1 + L2", 300),
    "p4_v12a": ("v12a", "baseline + public limits (8 min)", 480),
    "p4_v12b": ("v12b", "baseline + public sampling", 300),
    "p4_v12c": ("v12c", "baseline + public limits and prompt", 480),
    "p4_v16": ("v16", "baseline + public prompt at 5 min", 300),
    "p4_pub024": ("pub024", "public 0.24 notebook, unchanged", 480),
    "p4_pub024_6m": ("pub024-6m", "public notebook at 6 min", 360),
    "p4_v12b6": ("v12b6", "v12b with a 6-minute cap", 360),
    "p4_v15b": ("v15b", "v12b + L1 + L2", 300),
}


def sign_p(w: int, l: int) -> float:
    n = w + l
    if n == 0:
        return 1.0
    k = min(w, l)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)


def paired(a: str, b: str) -> tuple[int, int, float]:
    A, B = F.load(a), F.load(b)
    w = sum(bool(A[i]["resolved"]) and not B[i]["resolved"] for i in A)
    l = sum(bool(B[i]["resolved"]) and not A[i]["resolved"] for i in A)
    return w, l, sign_p(w, l)


def tab(name: str, cols: str, head: str, rows: list[str], note: str = "") -> None:
    body = "\n".join(rows)
    tex = (f"% generated by paper/arxiv/make_tex_tables.py\n\\begin{{tabular}}{{{cols}}}\n\\toprule\n{head} \\\\\n\\midrule\n"
           f"{body}\n\\bottomrule\n\\end{{tabular}}\n")
    if note:
        tex += note + "\n"
    (OUT / f"{name}.tex").write_text(tex)


def fmt_hidden(h: list[float]) -> str:
    return ", ".join(f"{x:.2f}" for x in h)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    sc = F.scores()
    # L4 screen
    rows = []
    for name, local, hidden in F.points(F.L4):
        rows.append(f"{name} & {', '.join(map(str, local))} & {fmt_hidden(hidden)} \\\\")
    tab("l4", "lrr", "configuration & local solves (of 74) & hidden public", rows)
    # A6000 calibration, sorted by local solves
    pts = F.points(F.A6000)
    pts.sort(key=lambda p: (st.mean(p[1]), st.mean(p[2])))
    rows = [f"{n} & {', '.join(map(str, l))} & {fmt_hidden(h)} \\\\" for n, l, h in pts]
    for n, (runs, refs) in F.TIMED_OUT.items():
        rows.append(f"{n} (8-min cap) & {', '.join(str(F.solved(r)) for r in runs)} & 12-h limit exceeded, {len(refs)} of {len(refs)} \\\\")
    tab("a6000", "lrr", "configuration & local solves (of 74) & hidden public", rows)
    # steps toward the public notebook, paired against the baseline run p4_v12
    steps = [("p4_v12a", "p4_v12", "public limits (8 min, 28 calls)"), ("p4_v12b", "p4_v12", "public sampling (temperature 0.2)"),
             ("p4_v12c", "p4_v12", "public limits and prompt"), ("p4_v16", "p4_v12", "public prompt restated for 5 min"),
             ("p4_v16", "p4_v12c", "\\quad same prompt: 5 min vs 8 min"), ("p4_pub024_6m", "p4_pub024", "public notebook cut to 6 min")]
    rows = []
    for a, b, label in steps:
        w, l, p = paired(a, b)
        rows.append(f"{label} & {F.solved(a)} & {F.solved(b)} & {w} & {l} & ${w - l:+d}$ & {p:.3f} \\\\")
    tab("steps", "lrrrrrr", "change & A & B & only A & only B & net & sign $p$", rows)
    # repeats on the box
    rows = []
    for a, b, label in (("p4_v13", "p4_v13r", "v13"), ("p4_v12", "p4_v12r", "v12 (baseline)")):
        A, B = F.load(a), F.load(b)
        flips = sum(bool(A[i]["resolved"]) != bool(B[i]["resolved"]) for i in A)
        w = sum(bool(B[i]["resolved"]) and not A[i]["resolved"] for i in A)
        exact = sum(bool(A[i]["resolved"]) == bool(B[i]["resolved"]) and A[i].get("calls") == B[i].get("calls")
                    and (A[i].get("patch") or "") == (B[i].get("patch") or "") and abs(A[i]["secs"] - B[i]["secs"]) <= 2 for i in A)
        rows.append(f"{label} & {F.solved(a)}, {F.solved(b)} & {flips} ({w}/{flips - w}) & {sign_p(w, flips - w):.3f} & {exact} \\\\")
    tab("repeats_box", "lrrrr", "configuration & solves & flips (gained/lost) & sign $p$ & exact replays", rows)
    reps = [("v4 (old scorer)", ["56591871", "56655519"]), ("v10.1", ["56690751", "56765412"]),
            ("v4h2 (edit helper)", ["56788077", "56864298"]), ("v12 (baseline)", ["57070001", "57390142"])]
    rows = [f"{n} & {', '.join(sc[r] for r in refs)} \\\\" for n, refs in reps]
    tab("repeats_hidden", "lr", "configuration & hidden public reads", rows)
    # every local run
    rows = []
    for run, (cid, desc, cap) in RUNS.items():
        d = F.load(run)
        secs = [r["secs"] for r in d.values()]
        rows.append(f"\\texttt{{{cid}}} & {desc} & {cap} & {F.solved(run)} & {st.mean(secs):.0f} & {120 * st.mean(secs) / 3600:.1f} \\\\")
    tab("runs", "llrrrr", "id & configuration & cap (s) & solved & mean s & 120-task h", rows)
    # Harness² improver sessions
    ss = H.sessions(ROOT / "eval" / "a6000" / "results" / "h2_gemma")
    label = {"inv1": "propose (invariant)", "dom1": "propose (domain)", "c1": "compose", "experience": "reflect"}
    rows = [f"{label[k]} & {v['sessions']} & {v['overflowed']} & {v['bare_keep_base']} \\\\" for k, v in
            sorted(ss.items(), key=lambda kv: ["inv1", "dom1", "c1", "experience"].index(kv[0]))]
    tot = {k: sum(v[k] for v in ss.values()) for k in ("sessions", "overflowed", "bare_keep_base")}
    rows.append(f"\\midrule\nall & {tot['sessions']} & {tot['overflowed']} & {tot['bare_keep_base']} \\\\")
    tab("h2_sessions", "lrrr", "stage & sessions & overflowed 32k & bare ``keep base''", rows)
    print(f"tables written to {OUT}: {sorted(p.name for p in OUT.glob('*.tex'))}")


if __name__ == "__main__":
    main()
