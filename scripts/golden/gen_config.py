"""Generate the self-contained agents-cli metric files and eval configs from eval/golden/golden_metrics.py.

    .venv/bin/python scripts/golden/gen_config.py            # write eval/golden/metrics/*.py and eval_config*.yaml
    .venv/bin/python scripts/golden/gen_config.py --check    # exit 1 listing every file that would change

Spec docs/eval/GOLDEN_EVALS_SPEC.md v1.1 section 7.1. agents-cli 1.7.0 execs a custom_function_file's source into a
fresh dict (no __file__, __name__ == "builtins", sys.path[0] = its own bin dir), so a metric file cannot import the
library: each eval/golden/metrics/<name>.py is the whole library source plus
    def evaluate(instance):
        return _score("<name>", instance)
Configs: eval_config_{L,F,V}.yaml run that suite's metrics then the X metrics (agents-cli runs every metric of a
config on every case, so one config per suite); eval_config.yaml runs all of them for a traces dir that mixes suites
(its agents-cli mean_score then averages the inapplicable zeros too: decisions read summary.py). Stdlib only.
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GOLDEN = os.path.join(ROOT, "eval", "golden")
LIB = os.path.join(GOLDEN, "golden_metrics.py")
HEADER = "# generated by scripts/golden/gen_config.py; do not edit\n"
FILE_HEADER = ("# generated by scripts/golden/gen_config.py from eval/golden/golden_metrics.py; do not edit\n"
               "# metric: %s\n")


def load_library(path=LIB):
    """(source, namespace) with the library exec'd exactly as agents-cli execs a metric file."""
    with open(path, encoding="utf-8") as f:
        src = f.read()
    ns = {}
    exec(compile(src, "<golden_metrics>", "exec"), ns)
    return src, ns


def metric_source(src, name):
    return (FILE_HEADER % name) + src.rstrip("\n") + "\n\n\ndef evaluate(instance):\n    return _score(\"%s\", instance)\n" \
        % name


def config_text(names, title):
    lines = [HEADER.rstrip("\n"), "# " + title, "metrics_to_run:"]
    lines += ["  - %s" % n for n in names]
    lines.append("custom_metrics:")
    for n in names:
        lines += ["  - name: %s" % n, "    custom_function_file: metrics/%s.py" % n, "    execution: local"]
    return "\n".join(lines) + "\n"


def expected_files(golden=GOLDEN, lib=LIB):
    """{absolute path: text} of every generated file."""
    src, ns = load_library(lib)
    metrics, names_for = ns["METRICS"], ns["metric_names"]
    out = {}
    for name in metrics:
        out[os.path.join(golden, "metrics", name + ".py")] = metric_source(src, name)
    for suite in "LFV":
        out[os.path.join(golden, "eval_config_%s.yaml" % suite)] = config_text(
            names_for(suite), "suite %s: its own metrics, then the X metrics (golden evals spec 7.1)" % suite)
    out[os.path.join(golden, "eval_config.yaml")] = config_text(
        names_for(None), "every metric (L, F, V, then X) for a traces dir that mixes suites; decisions read summary.py")
    return out


def drift(golden=GOLDEN, lib=LIB):
    """[(path, why)] for every generated file that differs, is missing, or is stale."""
    want = expected_files(golden, lib)
    bad = []
    for path, text in sorted(want.items()):
        if not os.path.isfile(path):
            bad.append((path, "missing"))
            continue
        with open(path, encoding="utf-8") as f:
            if f.read() != text:
                bad.append((path, "differs"))
    mdir = os.path.join(golden, "metrics")
    for fn in sorted(os.listdir(mdir)) if os.path.isdir(mdir) else []:
        p = os.path.join(mdir, fn)
        if fn.endswith(".py") and p not in want:
            bad.append((p, "stale (no such metric)"))
    return bad


def write(golden=GOLDEN, lib=LIB):
    """Write every generated file whose text changed and remove stale metric files. -> [(path, action)]."""
    want = expected_files(golden, lib)
    done = []
    os.makedirs(os.path.join(golden, "metrics"), exist_ok=True)
    for path, text in sorted(want.items()):
        old = None
        if os.path.isfile(path):
            with open(path, encoding="utf-8") as f:
                old = f.read()
        if old != text:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            done.append((path, "created" if old is None else "updated"))
    for path, why in drift(golden, lib):
        if why.startswith("stale"):
            os.remove(path)
            done.append((path, "removed"))
    return done


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when any generated file would change")
    ap.add_argument("--golden-dir", default=GOLDEN, help=argparse.SUPPRESS)
    ap.add_argument("--library", default=LIB, help=argparse.SUPPRESS)
    a = ap.parse_args(argv)
    rel = lambda p: os.path.relpath(p, ROOT)
    if a.check:
        bad = drift(a.golden_dir, a.library)
        for p, why in bad:
            print("DRIFT %s: %s" % (rel(p), why))
        n = len(expected_files(a.golden_dir, a.library))
        print(("gen_config --check: %d generated files in sync" % n) if not bad else
              "gen_config --check: %d of %d generated files drifted; run scripts/golden/gen_config.py" % (len(bad), n))
        return 1 if bad else 0
    done = write(a.golden_dir, a.library)
    for p, act in done:
        print("%s %s" % (act, rel(p)))
    print("gen_config: %d files changed" % len(done))
    return 0


if __name__ == "__main__":
    sys.exit(main())
